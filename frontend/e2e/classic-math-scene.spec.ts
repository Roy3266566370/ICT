import {test,expect} from '@playwright/test';
import {resolve} from 'node:path';

test('真实矩阵课件的数学图可编辑、保存、放映与重置',async({page},info)=>{
  test.setTimeout(360000);
  await page.goto('/living');
  await page.locator('input[type=file][accept*=".pptx"]').setInputFiles(resolve('..','用空间视角理解矩阵运算.pptx'));
  await expect(page).toHaveURL(/\/materials\/[^/]+\/work/,{timeout:60000});
  await page.getByRole('button',{name:'编辑课件'}).click({timeout:150000});
  const editor=page.locator('[data-free-editor]');
  await editor.getByRole('button',{name:'＋ 数学图'}).click({timeout:180000});
  const inline=editor.getByLabel('原位图形属性');
  await inline.getByLabel('A11',{exact:true}).fill('2');
  await inline.getByLabel('A12',{exact:true}).fill('0');
  await inline.getByLabel('线条颜色',{exact:true}).fill('#008844');
  await inline.getByLabel('线型',{exact:true}).selectOption('dotted');
  await inline.getByLabel('流动动画',{exact:true}).check();
  await inline.getByLabel('流速',{exact:true}).fill('2');
  const math=editor.locator('[data-math-scene]').last();
  await expect(math.locator('output')).toContainText('Av = (2, 1)');
  await expect(math).toHaveAttribute('data-line-style','dotted');
  const editorHandle=math.locator('.mafs-movable-point-hitbox');
  await editorHandle.scrollIntoViewIfNeeded();
  const editorBox=(await editorHandle.boundingBox())!;
  await page.mouse.move(editorBox.x+editorBox.width/2,editorBox.y+editorBox.height/2);
  await page.mouse.down();
  await page.mouse.move(editorBox.x+editorBox.width/2+20,editorBox.y+editorBox.height/2-10,{steps:6});
  await page.mouse.up();
  await expect(math.locator('output')).not.toContainText('Av = (2, 1)');
  await inline.getByLabel('向量 x',{exact:true}).fill('1');
  await inline.getByLabel('向量 y',{exact:true}).fill('1');
  await math.scrollIntoViewIfNeeded();
  const beforeMove=(await math.boundingBox())!;
  const oldLeft=await math.evaluate(e=>(e as HTMLElement).style.left);
  await page.mouse.move(beforeMove.x+20,beforeMove.y+20);
  await page.mouse.down();
  await page.mouse.move(beforeMove.x+45,beforeMove.y+35,{steps:6});
  await page.mouse.up();
  await expect(math).not.toHaveCSS('left',oldLeft);
  await expect(editor.getByText('已保存到服务端', {exact: true})).toBeVisible();
  await page.getByRole('button',{name:'互动预览'}).click();
  await expect(page).toHaveURL(/\/work/,{timeout:60000});
  await page.reload();
  const slide=page.getByLabel('幻灯片第 1 页',{exact:true});
  const saved=slide.locator('[data-math-scene]');
  await expect(saved).toHaveAttribute('data-flow','true');
  await expect(saved).toHaveAttribute('data-line-style','dotted');
  await expect(saved.locator('output')).toContainText('Av = (2, 1)');
  await page.getByRole('button',{name:'全屏放映'}).click();
  const controls=slide.getByLabel('放映数学图控制');
  await expect(controls.getByLabel('A11',{exact:true})).toHaveCount(0);
  await controls.getByLabel('向量 x',{exact:true}).fill('2');
  await expect(saved.locator('output')).toContainText('Av = (4, 1)');
  const handle=saved.locator('.mafs-movable-point-hitbox');
  const box=await handle.boundingBox();
  expect(box).not.toBeNull();
  await page.mouse.move(box!.x+box!.width/2,box!.y+box!.height/2);
  await page.mouse.down();
  await page.mouse.move(box!.x+box!.width/2+30,box!.y+box!.height/2-20,{steps:6});
  await page.mouse.up();
  await expect(saved.locator('output')).not.toContainText('Av = (4, 1)');
  await controls.getByLabel('变换进度',{exact:true}).fill('0');
  await controls.getByRole('button',{name:'播放变换',exact:true}).click();
  await expect(controls.getByLabel('变换进度',{exact:true})).not.toHaveValue('0');
  await controls.getByRole('button',{name:'暂停变换',exact:true}).click();
  await page.screenshot({path:info.outputPath('math-presentation.png')});
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'一键重置',exact:true}).click();
  await expect(saved.locator('output')).toContainText('Av = (2, 1)');
  await page.getByRole('button',{name:'查看原图',exact:true}).click();
  await expect(saved).toBeHidden();
  await page.getByRole('button',{name:'显示可操作图形',exact:true}).click();
  await expect(saved).toBeVisible();
  await page.getByRole('button',{name:'编辑课件'}).click();
  await editor.getByLabel('可编辑画布第 1 页',{exact:true}).locator('[data-math-scene]').click();
  await editor.getByLabel('对象属性').getByLabel('允许观众编辑',{exact:true}).uncheck();
  await expect(editor.getByText('已保存到服务端', {exact: true})).toBeVisible();
  await page.getByRole('button',{name:'互动预览'}).click();
  await expect(page).toHaveURL(/\/work/,{timeout:60000});
  await expect(slide.getByLabel('放映数学图控制').locator('input')).toHaveCount(0);
  await expect(slide.locator('.mafs-movable-point-hitbox')).toHaveCount(0);
  await page.getByRole('button',{name:'编辑课件'}).click();
  await editor.getByRole('button',{name:'＋ 数学图'}).click();
  const properties=editor.getByLabel('对象属性');
  await properties.getByLabel('变换进度',{exact:true}).fill('0');
  await editor.getByRole('button',{name:'图层',exact:true}).click();
  const layers=editor.getByTitle('矩阵变换图',{exact:true});
  await layers.nth(1).click();
  await properties.getByLabel('变换进度',{exact:true}).fill('0');
  await properties.getByRole('button',{name:'播放变换',exact:true}).click();
  await layers.nth(0).click();
  await expect(properties.getByRole('button',{name:'暂停变换',exact:true})).toHaveCount(0);
  await expect(properties.getByLabel('变换进度',{exact:true})).toHaveValue('0');
  await properties.getByRole('button',{name:'播放变换',exact:true}).click();
  await properties.getByRole('button',{name:'锁定对象',exact:true}).click();
  await expect(properties.getByRole('button',{name:'播放变换',exact:true})).toBeDisabled();
});
