import { test, expect, type Locator, type Page } from '@playwright/test';
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';

async function dragEnd(page: Page, drawing: Locator, deltaX: number, deltaY: number) {
  const handle = drawing.getByLabel('拖动终点');
  await expect(handle).toBeVisible();
  const box = (await handle.boundingBox())!;
  const x = box.x + box.width / 2;
  const y = box.y + box.height / 2;
  await page.mouse.move(x, y);
  await page.mouse.down();
  await page.mouse.move(x + deltaX, y + deltaY, { steps: 6 });
  await page.mouse.up();
}

test('真实矩阵课件的线条保存与放映可操作', async ({ page }, info) => {
  test.setTimeout(360_000);
  const file = resolve(process.env.E2E_LEGACY_PPTX ?? resolve('..', '用空间视角理解矩阵运算.pptx'));
  test.skip(!existsSync(file), '需要本地验收课件，可设置 E2E_LEGACY_PPTX');
  await page.goto('/living');
  await page.locator('input[type=file][accept*=".pptx"]').setInputFiles(file);
  await expect(page).toHaveURL(/\/materials\/[^/]+\/work/, { timeout: 60_000 });
  const edit = page.getByRole('link', { name: '编辑内容 / 交互' });
  await expect(edit).toBeVisible({ timeout: 150_000 });
  await edit.click();
  const editor = page.locator('[data-free-editor]');
  const addArrow = editor.getByRole('button', { name: '＋ 箭头' });
  await expect(addArrow).toBeEnabled({ timeout: 180_000 });
  await editor.getByRole('button', { name: '＋ 线条', exact: true }).click();
  await addArrow.click();
  const arrow = editor.locator('[data-vector-node]').last();
  const line = arrow.locator('[data-vector-stroke]');
  const originalX = await line.getAttribute('x2');
  const originalStart = Number(await line.getAttribute('x1'));
  await dragEnd(page, arrow, 55, -20);
  await expect(line).not.toHaveAttribute('x2', originalX!);
  expect(Number(await line.getAttribute('x1'))).toBeCloseTo(originalStart, 1);
  const inline = editor.getByLabel('原位图形属性');
  await inline.getByRole('spinbutton', { name: '线长', exact: true }).fill('225');
  await inline.getByLabel('线条颜色').fill('#ee3300');
  await inline.getByLabel('线型', { exact: true }).selectOption('dashed');
  await inline.getByLabel('流动动画', {exact:true}).check();
  await inline.getByLabel('流速', {exact:true}).fill('2');
  await expect(line).toHaveAttribute('stroke', '#ee3300');
  await expect(line).toHaveAttribute('stroke-dasharray', '9 6');
  await editor.getByRole('button', { name: '保存并返回演示' }).click();
  await expect(page).toHaveURL(/\/work/, { timeout: 60000 });
  await page.reload();
  const slide = page.getByLabel('幻灯片第 1 页', { exact: true });
  const savedArrow = slide.locator('[data-vector-node]').last();
  const savedLine = savedArrow.locator('[data-vector-stroke]');
  await expect(savedLine).toHaveAttribute('stroke', '#ee3300');
  await expect(savedLine).toHaveAttribute('stroke-dasharray', '9 6');
  await expect(savedLine).toHaveAttribute('marker-end', /url/);
  await expect(savedLine).toHaveClass(/sceneFlow/);
  await expect(savedLine).toHaveCSS('animation-duration', '0.5s');
  await page.getByRole('button', { name: /开始演示/ }).click();
  const controls = slide.getByLabel('放映线条控制');
  await controls.getByLabel('选择线条').selectOption({ index: 1 });
  await expect(controls.getByRole('spinbutton', { name: '线长', exact: true })).toHaveValue('225');
  const savedX = await savedLine.getAttribute('x2');
  await dragEnd(page, savedArrow, 45, 20);
  await expect(savedLine).not.toHaveAttribute('x2', savedX!);
  await controls.getByRole('spinbutton', { name: '线长', exact: true }).fill('270');
  await controls.getByLabel('线条颜色').fill('#007744');
  await controls.getByLabel('线型', { exact: true }).selectOption('dotted');
  await expect(savedLine).toHaveAttribute('stroke', '#007744');
  await expect(savedLine).toHaveAttribute('stroke-dasharray', '1 5');
  await expect(page).toHaveURL(/page=1/);
  await page.screenshot({ path: info.outputPath('vector-presentation.png') });
  await controls.getByRole('button', { name: '重置线条' }).click();
  await expect(savedLine).toHaveAttribute('stroke', '#ee3300');
  await expect(savedLine).toHaveAttribute('x2', savedX!);
});
